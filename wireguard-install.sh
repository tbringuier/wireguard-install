#!/bin/bash

# WireGuard server installer with public IP routing
# https://github.com/tbringuier/wireguard-install
#
# Fork of https://github.com/angristan/wireguard-install (MIT licence).
# Requires systemd. Tested on Debian, Ubuntu, Fedora, Rocky/Alma, Arch, openSUSE and Flatcar.
# Most of this fork was written with Claude (Anthropic) and reviewed by the maintainer.

RED='\033[0;31m'
ORANGE='\033[0;33m'
GREEN='\033[0;32m'
NC='\033[0m'

function isValidIpv4() {
	[[ $1 =~ ^((25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)\.){3}(25[0-5]|2[0-4][0-9]|[01]?[0-9][0-9]?)$ ]]
}

function isValidIpv6() {
	# Hex groups separated by colons, with at most one "::" shortcut
	[[ $1 =~ ^([0-9a-fA-F]{0,4}:){2,7}[0-9a-fA-F]{0,4}$ ]] && [[ $1 != *:::* ]] && [[ $(echo "$1" | grep -o '::' | wc -l) -le 1 ]]
}

function isValidHostname() {
	[[ $1 =~ ^[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?(\.[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?)*$ ]] && [[ $1 == *[A-Za-z]* ]]
}

function isPrivateIpv4() {
	# RFC 1918, RFC 6598 (carrier-grade NAT) and link-local ranges
	[[ $1 =~ ^10\. ]] ||
		[[ $1 =~ ^192\.168\. ]] ||
		[[ $1 =~ ^172\.(1[6-9]|2[0-9]|3[01])\. ]] ||
		[[ $1 =~ ^100\.(6[4-9]|[7-9][0-9]|1[01][0-9]|12[0-7])\. ]] ||
		[[ $1 =~ ^169\.254\. ]]
}

function buildClientAddressLine() {
	local PRIVATE_IPV4=$1
	local PUBLIC_IPV4=$2
	local PRIVATE_IPV6=$3
	local PUBLIC_IPV6=$4
	local ADDRESSES=""
	local ADDRESS

	for ADDRESS in \
		"${PUBLIC_IPV4:+${PUBLIC_IPV4}/32}" \
		"${PRIVATE_IPV4:+${PRIVATE_IPV4}/32}" \
		"${PUBLIC_IPV6:+${PUBLIC_IPV6}/128}" \
		"${PRIVATE_IPV6:+${PRIVATE_IPV6}/128}"; do
		if [[ -z ${ADDRESS} ]]; then
			continue
		elif [[ -z ${ADDRESSES} ]]; then
			ADDRESSES=${ADDRESS}
		else
			ADDRESSES="${ADDRESSES},${ADDRESS}"
		fi
	done

	echo "${ADDRESSES}"
}

function validateClientAddressMode() {
	local CLIENT_ADDRESS_MODE=$1
	local PRIVATE_IPV4=$2
	local PUBLIC_IPV4=$3
	local PRIVATE_IPV6=$4
	local PUBLIC_IPV6=$5

	case "${CLIENT_ADDRESS_MODE}" in
	private)
		[[ (-n ${PRIVATE_IPV4} || -n ${PRIVATE_IPV6}) && -z ${PUBLIC_IPV4} && -z ${PUBLIC_IPV6} ]]
		;;
	public)
		[[ (-n ${PUBLIC_IPV4} || -n ${PUBLIC_IPV6}) && -z ${PRIVATE_IPV4} && -z ${PRIVATE_IPV6} ]]
		;;
	mixed)
		[[ (-n ${PRIVATE_IPV4} || -n ${PRIVATE_IPV6}) && (-n ${PUBLIC_IPV4} || -n ${PUBLIC_IPV6}) ]]
		;;
	*)
		return 1
		;;
	esac
}

function buildPeerAllowedIps() {
	local PRIVATE_IPV4=$1
	local PUBLIC_IPV4=$2
	local PRIVATE_IPV6=$3
	local PUBLIC_IPV6=$4

	buildClientAddressLine "${PRIVATE_IPV4}" "${PUBLIC_IPV4}" "${PRIVATE_IPV6}" "${PUBLIC_IPV6}"
}

function buildSysctlConfig() {
	local PUBLIC_ROUTING_MODE=$1
	local SERVER_PUB_NIC=$2

	echo "net.ipv4.ip_forward = 1
net.ipv6.conf.all.forwarding = 1
# Forwarding makes the kernel ignore router advertisements unless accept_ra=2
net.ipv6.conf.${SERVER_PUB_NIC}.accept_ra = 2"

	if [[ ${PUBLIC_ROUTING_MODE} == "yes" ]]; then
		# Needed for the per-address NDP proxy entries added by the hooks
		echo "net.ipv6.conf.all.proxy_ndp = 1"
	fi
}

function applySysctlConfig() {
	# systemd-sysctl ships with systemd-udev on Enterprise Linux, which minimal images may lack
	if ! systemctl restart systemd-sysctl.service 2>/dev/null; then
		sysctl -q -p /etc/sysctl.d/wg.conf
	fi
}

function buildNftRuleset() {
	# buildNftRuleset <public nic> <wg nic> <wg ipv4> <wg ipv6> <wg mtu>
	local SERVER_PUB_NIC=$1
	local SERVER_WG_NIC=$2
	local SERVER_WG_IPV4=$3
	local SERVER_WG_IPV6=$4
	local SERVER_WG_MTU=$5
	local PRIVATE_IPV4_CIDR
	local PRIVATE_IPV6_CIDR
	local MSS_IPV4=$((SERVER_WG_MTU - 40))
	local MSS_IPV6=$((SERVER_WG_MTU - 60))

	PRIVATE_IPV4_CIDR=$(echo "${SERVER_WG_IPV4}" | awk -F '.' '{ print $1 "." $2 "." $3 ".0/24" }')
	PRIVATE_IPV6_CIDR="$(echo "${SERVER_WG_IPV6}" | awk -F '::' '{ print $1 }')::/64"

	# Accept rules belong to the host firewall: a separate nftables table cannot
	# override another table's drop policy, so this one only does what it owns.
	echo "# Generated by wireguard-install for ${SERVER_WG_NIC}: NAT for the private tunnel
# subnets and TCP MSS clamping to the tunnel MTU in both directions.
table inet wireguard
delete table inet wireguard
table inet wireguard {
	chain forward {
		type filter hook forward priority mangle; policy accept;
		meta nfproto ipv4 iifname \"${SERVER_WG_NIC}\" tcp flags syn tcp option maxseg size > ${MSS_IPV4} tcp option maxseg size set ${MSS_IPV4}
		meta nfproto ipv4 oifname \"${SERVER_WG_NIC}\" tcp flags syn tcp option maxseg size > ${MSS_IPV4} tcp option maxseg size set ${MSS_IPV4}
		meta nfproto ipv6 iifname \"${SERVER_WG_NIC}\" tcp flags syn tcp option maxseg size > ${MSS_IPV6} tcp option maxseg size set ${MSS_IPV6}
		meta nfproto ipv6 oifname \"${SERVER_WG_NIC}\" tcp flags syn tcp option maxseg size > ${MSS_IPV6} tcp option maxseg size set ${MSS_IPV6}
	}

	chain postrouting {
		type nat hook postrouting priority srcnat; policy accept;
		oifname \"${SERVER_PUB_NIC}\" ip saddr ${PRIVATE_IPV4_CIDR} masquerade
		oifname \"${SERVER_PUB_NIC}\" ip6 saddr ${PRIVATE_IPV6_CIDR} masquerade
	}
}"
}

function buildHookBlock() {
	# buildHookBlock <wg nic> <public nic> <public ipv4 list> <public ipv6 list>
	local SERVER_WG_NIC=$1
	local SERVER_PUB_NIC=$2
	local PUBLIC_IPV4_LIST=$3
	local PUBLIC_IPV6_LIST=$4
	local HOOKS
	local ADDRESS

	HOOKS="PostUp = nft -f /etc/wireguard/${SERVER_WG_NIC}.nft
PostDown = nft delete table inet wireguard || true"

	# Proxy ARP/NDP entries make the server answer for on-link public addresses
	while IFS= read -r ADDRESS; do
		[[ -n ${ADDRESS} ]] || continue
		HOOKS="${HOOKS}
PostUp = ip -4 neigh replace proxy ${ADDRESS} dev ${SERVER_PUB_NIC}
PostDown = ip -4 neigh del proxy ${ADDRESS} dev ${SERVER_PUB_NIC} || true"
	done <<<"${PUBLIC_IPV4_LIST}"

	while IFS= read -r ADDRESS; do
		[[ -n ${ADDRESS} ]] || continue
		HOOKS="${HOOKS}
PostUp = ip -6 neigh replace proxy ${ADDRESS} dev ${SERVER_PUB_NIC}
PostDown = ip -6 neigh del proxy ${ADDRESS} dev ${SERVER_PUB_NIC} || true"
	done <<<"${PUBLIC_IPV6_LIST}"

	echo "${HOOKS}"
}

function buildClientConfig() {
	local WG_INTERFACE_MTU=$1
	local CLIENT_PRIV_KEY=$2
	local SERVER_PUB_KEY=$3
	local CLIENT_PRE_SHARED_KEY=$4
	local ENDPOINT=$5
	local ALLOWED_IPS=$6
	local CLIENT_DNS_1=$7
	local CLIENT_DNS_2=$8
	local PRIVATE_IPV4=$9
	local PUBLIC_IPV4=${10}
	local PRIVATE_IPV6=${11}
	local PUBLIC_IPV6=${12}

	# No hooks: the server clamps the MSS for every flow, so phones and Windows work too
	echo "[Interface]
PrivateKey = ${CLIENT_PRIV_KEY}
Address = $(buildClientAddressLine "${PRIVATE_IPV4}" "${PUBLIC_IPV4}" "${PRIVATE_IPV6}" "${PUBLIC_IPV6}")
DNS = ${CLIENT_DNS_1},${CLIENT_DNS_2}
MTU = ${WG_INTERFACE_MTU}

[Peer]
PublicKey = ${SERVER_PUB_KEY}
PresharedKey = ${CLIENT_PRE_SHARED_KEY}
Endpoint = ${ENDPOINT}
AllowedIPs = ${ALLOWED_IPS}
PersistentKeepalive = 15"
}

function buildServerPeerBlock() {
	local CLIENT_NAME=$1
	local CLIENT_ADDRESS_MODE=$2
	local CLIENT_PUB_KEY=$3
	local CLIENT_PRE_SHARED_KEY=$4
	local PRIVATE_IPV4=$5
	local PUBLIC_IPV4=$6
	local PRIVATE_IPV6=$7
	local PUBLIC_IPV6=$8

	# Keepalives are only useful on the NATed side, so the client config carries them
	echo "### Client ${CLIENT_NAME}
# AddressMode: ${CLIENT_ADDRESS_MODE}
# PrivateIPv4: ${PRIVATE_IPV4}
# PublicIPv4: ${PUBLIC_IPV4}
# PrivateIPv6: ${PRIVATE_IPV6}
# PublicIPv6: ${PUBLIC_IPV6}
[Peer]
PublicKey = ${CLIENT_PUB_KEY}
PresharedKey = ${CLIENT_PRE_SHARED_KEY}
AllowedIPs = $(buildPeerAllowedIps "${PRIVATE_IPV4}" "${PUBLIC_IPV4}" "${PRIVATE_IPV6}" "${PUBLIC_IPV6}")"
}

function listPublicAddresses() {
	# listPublicAddresses <PublicIPv4|PublicIPv6> <peer blocks>
	echo "$2" | awk -F ': ' -v KEY="# $1: " 'index($0, KEY) == 1 && $2 != "" { print $2 }'
}

function getPeerBlocksFromConfig() {
	local WG_CONF_FILE=$1

	if [[ -e ${WG_CONF_FILE} ]]; then
		awk 'BEGIN { printing = 0 } /^### Client / { printing = 1 } printing { print }' "${WG_CONF_FILE}"
	fi
}

function writeServerConfig() {
	# writeServerConfig <config file> <peer blocks>
	local WG_CONF_FILE=$1
	local PEER_BLOCKS=$2

	printf '%s\n' "$(buildNftRuleset "${SERVER_PUB_NIC}" "${SERVER_WG_NIC}" "${SERVER_WG_IPV4}" "${SERVER_WG_IPV6}" "${SERVER_WG_MTU}")" >"/etc/wireguard/${SERVER_WG_NIC}.nft"
	chmod 600 "/etc/wireguard/${SERVER_WG_NIC}.nft"

	printf '[Interface]\nAddress = %s/24,%s/64\nListenPort = %s\nMTU = %s\nPrivateKey = %s\n' \
		"${SERVER_WG_IPV4}" \
		"${SERVER_WG_IPV6}" \
		"${SERVER_PORT}" \
		"${SERVER_WG_MTU}" \
		"${SERVER_PRIV_KEY}" >"${WG_CONF_FILE}"
	printf '%s\n' "$(buildHookBlock \
		"${SERVER_WG_NIC}" \
		"${SERVER_PUB_NIC}" \
		"$(listPublicAddresses PublicIPv4 "${PEER_BLOCKS}")" \
		"$(listPublicAddresses PublicIPv6 "${PEER_BLOCKS}")")" >>"${WG_CONF_FILE}"

	if [[ -n ${PEER_BLOCKS} ]]; then
		printf '\n%s\n' "${PEER_BLOCKS}" >>"${WG_CONF_FILE}"
	fi

	chmod 600 "${WG_CONF_FILE}"
}

function listProxyEntries() {
	# listProxyEntries <config file>: "<-4|-6> <address> dev <nic>" per proxy hook
	getHooksFromConfig "$1" | sed -n 's/^PostUp = ip \(-[46]\) neigh replace proxy \(.*\)$/\1 \2/p'
}

function getHooksFromConfig() {
	local WG_CONF_FILE=$1

	if [[ -e ${WG_CONF_FILE} ]]; then
		grep -E '^Post(Up|Down) = ' "${WG_CONF_FILE}"
	fi
}

function buildAnnouncementScript() {
	cat <<'SCRIPT'
#!/usr/bin/env python3
"""Announce public IPv4 addresses routed through WireGuard with gratuitous ARP.

Generated by wireguard-install: rewritten whenever clients change.

The upstream router must learn that these addresses live behind this host's
MAC address, and some providers only refresh their ARP caches from gratuitous
ARP. Every ANNOUNCE_INTERVAL seconds each address gets a gratuitous request
(RFC 5227) and a gratuitous reply. arping cannot do this for an address the
host does not own, hence the raw socket.
"""
import os
import socket
import struct
import sys
import time

BROADCAST = b"\xff" * 6
ETH_P_ARP = 0x0806


def arp_frame(operation, mac, ip):
    """Broadcast Ethernet frame carrying a gratuitous ARP request (1) or reply (2)."""
    target_mac = b"\x00" * 6 if operation == 1 else BROADCAST
    arp = struct.pack("!HHBBH6s4s6s4s", 1, 0x0800, 6, 4, operation, mac, ip, target_mac, ip)
    return BROADCAST + mac + struct.pack("!H", ETH_P_ARP) + arp


def main():
    nic = os.environ["SERVER_PUB_NIC"]
    addresses = os.environ["PUBLIC_IPV4_LIST"].split()
    interval = float(os.environ.get("ANNOUNCE_INTERVAL", "1"))

    with open(f"/sys/class/net/{nic}/address") as address_file:
        mac = bytes.fromhex(address_file.read().strip().replace(":", ""))
    sock = socket.socket(socket.AF_PACKET, socket.SOCK_RAW, socket.htons(ETH_P_ARP))
    sock.bind((nic, 0))
    frames = [arp_frame(op, mac, socket.inet_aton(a)) for a in addresses for op in (1, 2)]

    print(f"Announcing {' '.join(addresses)} on {nic} every {interval:g}s", flush=True)
    while True:
        for frame in frames:
            sock.send(frame)
        time.sleep(interval)


if __name__ == "__main__":
    try:
        main()
    except OSError as error:
        # Usually a missing or renamed interface: exit and let systemd retry
        print(f"Cannot announce on {os.environ.get('SERVER_PUB_NIC', '?')}: {error}", file=sys.stderr)
        sys.exit(1)
SCRIPT
}

function buildAnnouncementEnvironment() {
	local SERVER_PUB_NIC=$1
	local PUBLIC_IPV4_LIST=$2

	echo "# Generated by wireguard-install: rewritten whenever clients change.
SERVER_PUB_NIC=${SERVER_PUB_NIC}
PUBLIC_IPV4_LIST=\"${PUBLIC_IPV4_LIST}\"
ANNOUNCE_INTERVAL=1"
}

function buildAnnouncementSystemdUnit() {
	local PYTHON3=$1

	echo "[Unit]
Description=Announce public IPv4 addresses routed through WireGuard interface %i
Documentation=https://github.com/tbringuier/wireguard-install
BindsTo=wg-quick@%i.service
After=wg-quick@%i.service network-online.target
Wants=network-online.target
# Restarted on every client change, so the default start rate limit does not apply
StartLimitIntervalSec=0

[Service]
Type=simple
EnvironmentFile=/etc/wireguard/public-ipv4-announce-%i.env
ExecStart=${PYTHON3} /etc/wireguard/wg-public-ipv4-announce.py
Restart=always
RestartSec=5

# Sending raw ARP frames is all this service does
CapabilityBoundingSet=CAP_NET_RAW
NoNewPrivileges=true
ProtectSystem=strict
ProtectHome=true
PrivateTmp=true
ProtectKernelTunables=true
ProtectControlGroups=true

[Install]
WantedBy=wg-quick@%i.service"
}

function removeLegacyPublicIpv4AnnouncementService() {
	# Versions of this fork before October 2026 installed a non-template unit
	if [[ -e /etc/systemd/system/wg-public-ipv4-arping.service ]]; then
		systemctl disable --now wg-public-ipv4-arping.service >/dev/null 2>&1 || true
		rm -f /etc/systemd/system/wg-public-ipv4-arping.service
		rm -f /etc/wireguard/wg-public-ipv4-arping.sh /etc/wireguard/public-ipv4.list
		systemctl daemon-reload
	fi
}

function refreshPublicIpv4AnnouncementService() {
	local WG_CONF_FILE="/etc/wireguard/${SERVER_WG_NIC}.conf"
	local UNIT="wg-public-ipv4-announce@${SERVER_WG_NIC}.service"
	local ENV_FILE="/etc/wireguard/public-ipv4-announce-${SERVER_WG_NIC}.env"
	local PUBLIC_IPV4_LIST
	local PYTHON3

	if [[ ${PUBLIC_ROUTING_MODE} != 'yes' ]]; then
		return
	fi

	removeLegacyPublicIpv4AnnouncementService

	PUBLIC_IPV4_LIST=$(listPublicAddresses PublicIPv4 "$(getPeerBlocksFromConfig "${WG_CONF_FILE}")" | paste -sd ' ')

	if [[ -z ${PUBLIC_IPV4_LIST} ]]; then
		# Nothing to announce: keep the unit file around but inactive
		systemctl disable --now "${UNIT}" >/dev/null 2>&1 || true
		rm -f "${ENV_FILE}"
		return
	fi

	if ! PYTHON3=$(command -v python3); then
		echo -e "${ORANGE}python3 is not available: public IPv4 addresses are not announced with gratuitous ARP.${NC}"
		echo -e "${ORANGE}The server still answers ARP requests for them (proxy ARP), which is enough with most providers.${NC}"
		return
	fi

	printf '%s\n' "$(buildAnnouncementScript)" >/etc/wireguard/wg-public-ipv4-announce.py
	chmod 600 /etc/wireguard/wg-public-ipv4-announce.py
	printf '%s\n' "$(buildAnnouncementEnvironment "${SERVER_PUB_NIC}" "${PUBLIC_IPV4_LIST}")" >"${ENV_FILE}"
	chmod 600 "${ENV_FILE}"
	printf '%s\n' "$(buildAnnouncementSystemdUnit "${PYTHON3}")" >/etc/systemd/system/wg-public-ipv4-announce@.service

	# The unit is wanted by wg-quick@<interface>, so it follows the tunnel across reboots
	systemctl daemon-reload
	systemctl enable "${UNIT}" >/dev/null 2>&1
	if ! systemctl restart "${UNIT}"; then
		echo -e "${ORANGE}The public IPv4 announcement service could not be started, check: journalctl -u ${UNIT}${NC}"
	fi
}

function removePublicIpv4AnnouncementService() {
	removeLegacyPublicIpv4AnnouncementService

	systemctl disable --now "wg-public-ipv4-announce@${SERVER_WG_NIC}.service" >/dev/null 2>&1 || true
	rm -f /etc/systemd/system/wg-public-ipv4-announce@.service
	rm -f /etc/wireguard/wg-public-ipv4-announce.py "/etc/wireguard/public-ipv4-announce-${SERVER_WG_NIC}.env"
	systemctl daemon-reload
}

function applyServerConfig() {
	# applyServerConfig <peer blocks>
	# Regenerates the server configuration and applies it live: peers through
	# wg syncconf, proxy ARP/NDP entries through ip neigh. Only a change in the
	# other hooks (a migration, an edited parameter) stops and starts the tunnel,
	# since wg-quick runs PostDown from the file on disk.
	local PEER_BLOCKS=$1
	local WG_CONF_FILE="/etc/wireguard/${SERVER_WG_NIC}.conf"
	local NEW_CONF_FILE="${WG_CONF_FILE}.new"
	local UNIT="wg-quick@${SERVER_WG_NIC}.service"
	local TUNNEL_ACTIVE=no
	local PROXIES_BEFORE
	local PROXIES_AFTER
	local ENTRY

	writeServerConfig "${NEW_CONF_FILE}" "${PEER_BLOCKS}"

	if systemctl is-active --quiet "${UNIT}"; then
		TUNNEL_ACTIVE=yes
	fi

	if [[ ${TUNNEL_ACTIVE} == yes && $(getHooksFromConfig "${WG_CONF_FILE}" | grep -v ' neigh ') != "$(getHooksFromConfig "${NEW_CONF_FILE}" | grep -v ' neigh ')" ]]; then
		systemctl stop "${UNIT}"
		TUNNEL_ACTIVE=no
	fi

	PROXIES_BEFORE=$(listProxyEntries "${WG_CONF_FILE}" | sort)
	PROXIES_AFTER=$(listProxyEntries "${NEW_CONF_FILE}" | sort)
	cp -p "${WG_CONF_FILE}" "${WG_CONF_FILE}.bak"
	mv "${NEW_CONF_FILE}" "${WG_CONF_FILE}"

	if [[ ${TUNNEL_ACTIVE} == yes ]]; then
		wg syncconf "${SERVER_WG_NIC}" <(wg-quick strip "${SERVER_WG_NIC}")
		while read -r ENTRY; do
			# shellcheck disable=SC2086
			[[ -n ${ENTRY} ]] && ip ${ENTRY%% *} neigh del proxy ${ENTRY#* } 2>/dev/null
		done <<<"$(comm -23 <(echo "${PROXIES_BEFORE}") <(echo "${PROXIES_AFTER}"))"
		while read -r ENTRY; do
			# shellcheck disable=SC2086
			[[ -n ${ENTRY} ]] && ip ${ENTRY%% *} neigh replace proxy ${ENTRY#* }
		done <<<"$(comm -13 <(echo "${PROXIES_BEFORE}") <(echo "${PROXIES_AFTER}"))"
	else
		systemctl start "${UNIT}"
	fi

	refreshPublicIpv4AnnouncementService
}

function installPackages() {
	if ! "$@"; then
		echo -e "${RED}Failed to install packages.${NC}"
		echo "Please check your internet connection and package sources."
		exit 1
	fi
}

function installOptionalPackages() {
	if ! "$@"; then
		echo -e "${ORANGE}Optional packages could not be installed, continuing without them.${NC}"
	fi
}

function hasWireGuardKernelSupport() {
	# Creating an interface is the only reliable test: the module may be built in,
	# autoloaded, or missing on a kernel older than 5.6.
	modprobe wireguard >/dev/null 2>&1 || true
	if ip link add wg-probe type wireguard >/dev/null 2>&1; then
		ip link del wg-probe
		return 0
	fi
	return 1
}

function isRoot() {
	if [ "${EUID}" -ne 0 ]; then
		echo "You need to run this script as root"
		exit 1
	fi
}

function checkSystemd() {
	if [[ ! -d /run/systemd/system ]] || ! command -v systemctl &>/dev/null; then
		echo "This script requires systemd as the init system."
		exit 1
	fi
}

function waitForCloudInit() {
	# A fresh cloud instance may still be configured by cloud-init
	if command -v cloud-init &>/dev/null && [[ -d /run/cloud-init ]]; then
		if ! cloud-init status >/dev/null 2>&1; then
			return
		fi
		if [[ $(cloud-init status 2>/dev/null) == *running* ]]; then
			echo "Waiting for cloud-init to finish..."
			cloud-init status --wait >/dev/null 2>&1 || true
		fi
	fi
}

function checkVirt() {
	VIRT=$(systemd-detect-virt)
	if [[ ${VIRT} == "openvz" ]]; then
		echo "OpenVZ is not supported"
		exit 1
	fi
	if [[ ${VIRT} == "lxc" ]]; then
		echo "LXC is not supported (yet)."
		echo "WireGuard can technically run in an LXC container,"
		echo "but the kernel module has to be installed on the host,"
		echo "the container has to be run with some specific parameters"
		echo "and only the tools need to be installed in the container."
		exit 1
	fi
}

function checkOS() {
	if [[ ! -e /etc/os-release ]]; then
		echo "Unable to detect the distribution: /etc/os-release is missing."
		exit 1
	fi
	source /etc/os-release
	OS="${ID}"
	OS_FAMILY=""

	# Map the distribution (or the ones it derives from) to a package family
	local CANDIDATE
	for CANDIDATE in ${ID} ${ID_LIKE:-}; do
		case "${CANDIDATE}" in
		debian | ubuntu | raspbian)
			OS_FAMILY=debian
			;;
		fedora | rhel | centos | almalinux | rocky | ol)
			OS_FAMILY=rhel
			;;
		arch | archarm | manjaro)
			OS_FAMILY=arch
			;;
		suse | opensuse | opensuse-leap | opensuse-tumbleweed | sles)
			OS_FAMILY=suse
			;;
		flatcar)
			OS_FAMILY=flatcar
			;;
		*)
			continue
			;;
		esac
		break
	done

	# Unknown distribution: fall back on the package manager that is available
	if [[ -z ${OS_FAMILY} ]]; then
		if command -v apt-get &>/dev/null; then
			OS_FAMILY=debian
		elif command -v dnf &>/dev/null; then
			OS_FAMILY=rhel
		elif command -v pacman &>/dev/null; then
			OS_FAMILY=arch
		elif command -v zypper &>/dev/null; then
			OS_FAMILY=suse
		else
			echo "Looks like you aren't running this installer on a supported system (${PRETTY_NAME:-${ID}})."
			echo "Supported package managers: apt-get, dnf, pacman, zypper. Flatcar Linux is supported as-is."
			exit 1
		fi
	fi

	# Reject releases whose kernel or repositories predate WireGuard
	local MAJOR_VERSION="${VERSION_ID%%.*}"
	if [[ -n ${MAJOR_VERSION} && ${MAJOR_VERSION} =~ ^[0-9]+$ ]]; then
		case "${OS}" in
		debian | raspbian)
			if [[ ${MAJOR_VERSION} -lt 11 ]]; then
				echo "Your version of Debian (${VERSION_ID}) is not supported. Please use Debian 11 Bullseye or later"
				exit 1
			fi
			;;
		ubuntu)
			if [[ ${MAJOR_VERSION} -lt 20 ]]; then
				echo "Your version of Ubuntu (${VERSION_ID}) is not supported. Please use Ubuntu 20.04 or later"
				exit 1
			fi
			;;
		fedora)
			if [[ ${MAJOR_VERSION} -lt 32 ]]; then
				echo "Your version of Fedora (${VERSION_ID}) is not supported. Please use Fedora 32 or later"
				exit 1
			fi
			;;
		centos | almalinux | rocky | rhel | ol)
			if [[ ${MAJOR_VERSION} -lt 8 ]]; then
				echo "Your version of ${PRETTY_NAME:-${ID}} is not supported. Please use release 8 or later"
				exit 1
			fi
			;;
		esac
	fi
}

function getHomeDirForClient() {
	local CLIENT_NAME=$1

	if [[ -z ${CLIENT_NAME} ]]; then
		echo "Error: getHomeDirForClient() requires a client name as argument"
		exit 1
	fi

	# Prefer the home of a user named like the client, then the sudo caller's, then root's
	if [[ -e "/home/${CLIENT_NAME}" ]]; then
		echo "/home/${CLIENT_NAME}"
	elif [[ -n ${SUDO_USER:-} && ${SUDO_USER} != root ]]; then
		echo "/home/${SUDO_USER}"
	else
		echo "/root"
	fi
}

