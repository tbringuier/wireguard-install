function fetchPublicIpv4() {
	local URL
	local ADDRESS

	for URL in https://api.ipify.org https://ifconfig.me/ip https://icanhazip.com; do
		if command -v curl &>/dev/null; then
			ADDRESS=$(curl -4 -fsS --max-time 5 "${URL}" 2>/dev/null)
		elif command -v wget &>/dev/null; then
			ADDRESS=$(wget -4 -qO- --timeout=5 "${URL}" 2>/dev/null)
		else
			return 1
		fi
		ADDRESS=$(echo "${ADDRESS}" | tr -d '[:space:]')
		if isValidIpv4 "${ADDRESS}"; then
			echo "${ADDRESS}"
			return 0
		fi
	done

	return 1
}

function detectPublicIp() {
	local ADDRESS
	local EXTERNAL_ADDRESS

	ADDRESS=$(ip -4 -o addr show scope global 2>/dev/null | awk '{ print $4 }' | cut -d '/' -f 1 | head -1)
	if [[ -n ${ADDRESS} ]] && isPrivateIpv4 "${ADDRESS}"; then
		# Cloud instances behind 1:1 NAT only carry a private address
		EXTERNAL_ADDRESS=$(fetchPublicIpv4) && ADDRESS=${EXTERNAL_ADDRESS}
	fi
	if [[ -z ${ADDRESS} ]]; then
		ADDRESS=$(ip -6 -o addr show scope global 2>/dev/null | awk '{ print $4 }' | cut -d '/' -f 1 | head -1)
	fi

	echo "${ADDRESS}"
}

function detectPublicNic() {
	local NIC

	NIC=$(ip -4 -o route show default 2>/dev/null | awk '{ for (i = 1; i <= NF; i++) if ($i == "dev") print $(i + 1) }' | head -1)
	if [[ -z ${NIC} ]]; then
		NIC=$(ip -6 -o route show default 2>/dev/null | awk '{ for (i = 1; i <= NF; i++) if ($i == "dev") print $(i + 1) }' | head -1)
	fi

	echo "${NIC}"
}

function installQuestions() {
	echo "Welcome to the WireGuard installer!"
	echo "The git repository is available at: https://github.com/tbringuier/wireguard-install"
	echo ""
	echo "I need to ask you a few questions before starting the setup."
	echo "You can keep the default options and just press enter if you are ok with them."
	echo ""

	# Detect public IPv4 or IPv6 address and pre-fill for the user
	SERVER_PUB_IP=$(detectPublicIp)
	until isValidIpv4 "${SERVER_PUB_IP}" || isValidIpv6 "${SERVER_PUB_IP//[\[\]]/}" || isValidHostname "${SERVER_PUB_IP}"; do
		read -rp "Public IPv4, IPv6 or hostname of this server: " -e -i "${SERVER_PUB_IP}" SERVER_PUB_IP
	done

	# Detect public interface and pre-fill for the user
	SERVER_NIC=$(detectPublicNic)
	until [[ ${SERVER_PUB_NIC} =~ ^[a-zA-Z0-9_]+$ ]]; do
		read -rp "Public interface: " -e -i "${SERVER_NIC}" SERVER_PUB_NIC
	done

	until [[ ${SERVER_WG_NIC} =~ ^[a-zA-Z0-9_]+$ && ${#SERVER_WG_NIC} -lt 16 ]]; do
		read -rp "WireGuard interface name: " -e -i wg0 SERVER_WG_NIC
	done

	# Tunnel MTU: the public link minus the WireGuard overhead, capped at the usual 1420
	DEFAULT_WG_MTU=$(($(cat "/sys/class/net/${SERVER_PUB_NIC}/mtu" 2>/dev/null || echo 1500) - 80))
	if [[ ${DEFAULT_WG_MTU} -gt 1420 ]]; then
		DEFAULT_WG_MTU=1420
	elif [[ ${DEFAULT_WG_MTU} -lt 1280 ]]; then
		DEFAULT_WG_MTU=1280
	fi
	until [[ ${SERVER_WG_MTU} =~ ^[0-9]+$ ]] && [[ ${SERVER_WG_MTU} -ge 1280 && ${SERVER_WG_MTU} -le 1500 ]]; do
		read -rp "Tunnel MTU [1280-1500]: " -e -i "${DEFAULT_WG_MTU}" SERVER_WG_MTU
	done

	until isValidIpv4 "${SERVER_WG_IPV4}"; do
		read -rp "Server WireGuard IPv4: " -e -i 10.66.66.1 SERVER_WG_IPV4
	done

	until [[ ${SERVER_WG_IPV6} =~ ^([a-f0-9]{1,4}:){3,4}: ]]; do
		read -rp "Server WireGuard IPv6: " -e -i fd42:42:42::1 SERVER_WG_IPV6
	done

	# Generate random number within private ports range
	RANDOM_PORT=$(shuf -i49152-65535 -n1)
	until [[ ${SERVER_PORT} =~ ^[0-9]+$ ]] && [ "${SERVER_PORT}" -ge 1 ] && [ "${SERVER_PORT}" -le 65535 ]; do
		read -rp "Server WireGuard port [1-65535]: " -e -i "${RANDOM_PORT}" SERVER_PORT
	done

	# Cloudflare DNS by default
	until isValidIpv4 "${CLIENT_DNS_1}" || isValidIpv6 "${CLIENT_DNS_1}"; do
		read -rp "First DNS resolver to use for the clients: " -e -i 1.1.1.1 CLIENT_DNS_1
	done
	until isValidIpv4 "${CLIENT_DNS_2}" || isValidIpv6 "${CLIENT_DNS_2}"; do
		read -rp "Second DNS resolver to use for the clients (optional): " -e -i 1.0.0.1 CLIENT_DNS_2
		if [[ ${CLIENT_DNS_2} == "" ]]; then
			CLIENT_DNS_2="${CLIENT_DNS_1}"
		fi
	done

	until [[ ${PUBLIC_ROUTING_MODE} =~ ^(yes|no)$ ]]; do
		read -rp "Enable public IP routing support [yes/no]: " -e -i no PUBLIC_ROUTING_MODE
	done

	until [[ ${ALLOWED_IPS} =~ ^.+$ ]]; do
		echo -e "\nWireGuard uses a parameter called AllowedIPs to determine what is routed over the VPN."
		read -rp "Allowed IPs list for generated clients (leave default to route everything): " -e -i '0.0.0.0/0,::/0' ALLOWED_IPS
		if [[ ${ALLOWED_IPS} == "" ]]; then
			ALLOWED_IPS="0.0.0.0/0,::/0"
		fi
	done

	echo ""
	echo "Okay, that was all I needed. We are ready to setup your WireGuard server now."
	echo "You will be able to generate a client at the end of the installation."
	read -n1 -r -p "Press any key to continue..."
}

function installWireGuard() {
	# Run setup questions first
	installQuestions

	# Install WireGuard tools and module
	case "${OS_FAMILY}" in
	debian)
		export DEBIAN_FRONTEND=noninteractive
		# cloud-init or unattended-upgrades may still hold the dpkg lock after boot
		local APT_GET=(apt-get -o DPkg::Lock::Timeout=300)
		"${APT_GET[@]}" update
		installPackages "${APT_GET[@]}" install -y wireguard-tools nftables
		if ! hasWireGuardKernelSupport; then
			# Kernel older than 5.6: the metapackage pulls the DKMS module
			installOptionalPackages "${APT_GET[@]}" install -y wireguard
		fi
		installOptionalPackages "${APT_GET[@]}" install -y qrencode
		if [[ ${PUBLIC_ROUTING_MODE} == 'yes' ]]; then
			installOptionalPackages "${APT_GET[@]}" install -y python3
		fi
		;;
	rhel)
		if [[ ${OS} == 'ol' && ${VERSION_ID%%.*} == 8 ]]; then
			# Oracle Linux 8 ships wireguard-tools in the UEK R6 developer repository
			installPackages dnf install -y oraclelinux-developer-release-el8
			dnf config-manager --disable -y ol8_developer
			dnf config-manager --enable -y ol8_developer_UEKR6
			dnf config-manager --save -y --setopt=ol8_developer_UEKR6.includepkgs='wireguard-tools*'
		elif [[ ${OS} != 'fedora' && ${VERSION_ID%%.*} == 8 ]]; then
			# The EL8 kernel predates WireGuard: use the ELRepo kernel module
			installOptionalPackages dnf install -y epel-release elrepo-release
			installPackages dnf install -y kmod-wireguard
		elif [[ ${OS} != 'fedora' ]]; then
			# qrencode lives in EPEL on Enterprise Linux
			installOptionalPackages dnf install -y epel-release
		fi
		installPackages dnf install -y wireguard-tools nftables
		installOptionalPackages dnf install -y qrencode
		if [[ ${PUBLIC_ROUTING_MODE} == 'yes' ]]; then
			installOptionalPackages dnf install -y python3
		fi
		;;
	arch)
		installPackages pacman -S --needed --noconfirm wireguard-tools nftables
		installOptionalPackages pacman -S --needed --noconfirm qrencode
		if [[ ${PUBLIC_ROUTING_MODE} == 'yes' ]]; then
			installOptionalPackages pacman -S --needed --noconfirm python
		fi
		;;
	suse)
		installPackages zypper --non-interactive install wireguard-tools nftables
		installOptionalPackages zypper --non-interactive install qrencode
		if [[ ${PUBLIC_ROUTING_MODE} == 'yes' ]]; then
			installOptionalPackages zypper --non-interactive install python3
		fi
		;;
	flatcar)
		# Flatcar ships WireGuard and nftables in its read-only /usr
		;;
	esac

	# Verify WireGuard installation
	if ! command -v wg &>/dev/null; then
		echo -e "${RED}WireGuard installation failed. The 'wg' command was not found.${NC}"
		echo "Please check the installation output above for errors."
		exit 1
	fi
	if ! hasWireGuardKernelSupport; then
		echo -e "${ORANGE}The running kernel has no WireGuard support. If the kernel was just updated, reboot and run this script again.${NC}"
	fi
	if ! command -v nft &>/dev/null; then
		echo -e "${RED}The nft command is required (nftables package).${NC}"
		exit 1
	fi

	# Make sure the directory exists with restrictive permissions
	install -d -m 700 /etc/wireguard

	SERVER_PRIV_KEY=$(wg genkey)
	SERVER_PUB_KEY=$(echo "${SERVER_PRIV_KEY}" | wg pubkey)

	# Save WireGuard settings
	echo "SERVER_PUB_IP=${SERVER_PUB_IP}
SERVER_PUB_NIC=${SERVER_PUB_NIC}
SERVER_WG_NIC=${SERVER_WG_NIC}
SERVER_WG_IPV4=${SERVER_WG_IPV4}
SERVER_WG_IPV6=${SERVER_WG_IPV6}
SERVER_PORT=${SERVER_PORT}
SERVER_PRIV_KEY=${SERVER_PRIV_KEY}
SERVER_PUB_KEY=${SERVER_PUB_KEY}
CLIENT_DNS_1=${CLIENT_DNS_1}
CLIENT_DNS_2=${CLIENT_DNS_2}
ALLOWED_IPS=${ALLOWED_IPS}
PUBLIC_ROUTING_MODE=${PUBLIC_ROUTING_MODE}
SERVER_WG_MTU=${SERVER_WG_MTU}" >/etc/wireguard/params
	chmod 600 /etc/wireguard/params

	# Add server interface
	writeServerConfig "/etc/wireguard/${SERVER_WG_NIC}.conf" ""

	# Enable routing on the server
	install -d /etc/sysctl.d
	printf '%s\n' "$(buildSysctlConfig "${PUBLIC_ROUTING_MODE}" "${SERVER_PUB_NIC}")" >/etc/sysctl.d/wg.conf
	applySysctlConfig

	systemctl enable --now "wg-quick@${SERVER_WG_NIC}"

	refreshPublicIpv4AnnouncementService

	newClient
	echo -e "${GREEN}If you want to add more clients, you simply need to run this script another time!${NC}"

	# Check if WireGuard is running
	systemctl is-active --quiet "wg-quick@${SERVER_WG_NIC}"
	WG_RUNNING=$?

	# WireGuard might not work if we updated the kernel. Tell the user to reboot
	if [[ ${WG_RUNNING} -ne 0 ]]; then
		echo -e "\n${RED}WARNING: WireGuard does not seem to be running.${NC}"
		echo -e "${ORANGE}You can check if WireGuard is running with: systemctl status wg-quick@${SERVER_WG_NIC}${NC}"
		echo -e "${ORANGE}If you get something like \"Cannot find device ${SERVER_WG_NIC}\", please reboot!${NC}"
	else # WireGuard is running
		echo -e "\n${GREEN}WireGuard is running.${NC}"
		echo -e "${GREEN}You can check the status of WireGuard with: systemctl status wg-quick@${SERVER_WG_NIC}\n\n${NC}"
		echo -e "${ORANGE}If you don't have internet connectivity from your client, try to reboot the server.${NC}"
	fi
}

function readClientAddress() {
	# readClientAddress <variable> <prompt> <default> <ipv4|ipv6> <private|public>
	# Asks for an address until it is empty (unused), valid and not taken yet.
	local VARIABLE=$1
	local PROMPT=$2
	local DEFAULT=$3
	local FAMILY=$4
	local SCOPE=$5
	local WG_CONF_FILE="/etc/wireguard/${SERVER_WG_NIC}.conf"
	local VALUE
	local PREFIX_LENGTH=32

	if [[ ${FAMILY} == ipv6 ]]; then
		PREFIX_LENGTH=128
	fi

	while :; do
		read -rp "${PROMPT} (leave empty if unused): " -e -i "${DEFAULT}" VALUE
		if [[ -z ${VALUE} ]]; then
			break
		fi

		if [[ ${FAMILY} == ipv4 ]] && ! isValidIpv4 "${VALUE}"; then
			echo -e "${ORANGE}${VALUE} is not a valid IPv4 address.${NC}"
		elif [[ ${FAMILY} == ipv6 ]] && ! isValidIpv6 "${VALUE}"; then
			echo -e "${ORANGE}${VALUE} is not a valid IPv6 address.${NC}"
		elif [[ ${VALUE} == "${SERVER_WG_IPV4}" || ${VALUE} == "${SERVER_WG_IPV6}" || ${VALUE} == "${SERVER_PUB_IP//[\[\]]/}" ]]; then
			echo -e "${ORANGE}${VALUE} is used by the server itself, please choose another address.${NC}"
		elif [[ ${SCOPE} == public ]] && [[ -n $(ip -o addr show to "${VALUE}" 2>/dev/null) ]]; then
			echo -e "${ORANGE}${VALUE} is configured on a network interface of this server, so it cannot be routed to a client.${NC}"
			echo -e "${ORANGE}Remove it from the network configuration (cloud-init, netplan, NetworkManager...) first.${NC}"
		elif grep -q -F "${VALUE}/${PREFIX_LENGTH}" "${WG_CONF_FILE}"; then
			echo -e "${ORANGE}A client with the address ${VALUE} was already created, please choose another one.${NC}"
		else
			break
		fi
		echo ""
	done

	printf -v "${VARIABLE}" '%s' "${VALUE}"
}

function newClient() {
	local WG_CONF_FILE="/etc/wireguard/${SERVER_WG_NIC}.conf"

	# If SERVER_PUB_IP is IPv6, add brackets if missing
	if [[ ${SERVER_PUB_IP} =~ .*:.* ]]; then
		if [[ ${SERVER_PUB_IP} != *"["* ]] || [[ ${SERVER_PUB_IP} != *"]"* ]]; then
			SERVER_PUB_IP="[${SERVER_PUB_IP}]"
		fi
	fi
	ENDPOINT="${SERVER_PUB_IP}:${SERVER_PORT}"

	echo ""
	echo "Client configuration"
	echo ""
	echo "The client name must consist of alphanumeric character(s). It may also include underscores or dashes and can't exceed 15 chars."

	until [[ ${CLIENT_NAME} =~ ^[a-zA-Z0-9_-]+$ && ${CLIENT_EXISTS} == '0' && ${#CLIENT_NAME} -lt 16 ]]; do
		read -rp "Client name: " -e CLIENT_NAME
		CLIENT_EXISTS=$(grep -c -E "^### Client ${CLIENT_NAME}\$" "${WG_CONF_FILE}")

		if [[ ${CLIENT_EXISTS} != 0 ]]; then
			echo ""
			echo -e "${ORANGE}A client with the specified name was already created, please choose another name.${NC}"
			echo ""
		fi
	done

	if [[ ${PUBLIC_ROUTING_MODE} == 'yes' ]]; then
		echo ""
		echo "A private client gets an address from the tunnel subnet and is NATed behind the server."
		echo "A public client gets one of the server's additional public addresses, routed without NAT."
		echo "A mixed client gets both."
		until [[ ${CLIENT_ADDRESS_MODE} =~ ^(private|public|mixed)$ ]]; do
			read -rp "Client address mode [private/public/mixed]: " -e -i private CLIENT_ADDRESS_MODE
		done
	else
		CLIENT_ADDRESS_MODE=private
	fi

	CLIENT_PRIVATE_IPV4=""
	CLIENT_PRIVATE_IPV6=""
	CLIENT_PUBLIC_IPV4=""
	CLIENT_PUBLIC_IPV6=""

	if [[ ${CLIENT_ADDRESS_MODE} != 'public' ]]; then
		BASE_IPV4=$(echo "${SERVER_WG_IPV4}" | awk -F '.' '{ print $1"."$2"."$3 }')
		BASE_IPV6=$(echo "${SERVER_WG_IPV6}" | awk -F '::' '{ print $1 }')

		# Pick the first free host address of the tunnel subnet
		for DOT_IP in {2..254}; do
			DOT_EXISTS=$(grep -c -F "${BASE_IPV4}.${DOT_IP}/32" "${WG_CONF_FILE}")
			if [[ ${DOT_EXISTS} == '0' ]]; then
				break
			fi
		done

		if [[ ${DOT_EXISTS} != '0' ]]; then
			echo ""
			echo "The subnet configured supports only 253 clients."
			exit 1
		fi

		readClientAddress CLIENT_PRIVATE_IPV4 "Private client IPv4" "${BASE_IPV4}.${DOT_IP}" ipv4 private
		readClientAddress CLIENT_PRIVATE_IPV6 "Private client IPv6" "${BASE_IPV6}::${DOT_IP}" ipv6 private
	fi

	if [[ ${CLIENT_ADDRESS_MODE} != 'private' ]]; then
		echo ""
		echo "Public addresses must be routed to this server by your provider (additional/failover IP)."
		readClientAddress CLIENT_PUBLIC_IPV4 "Public client IPv4" "" ipv4 public
		readClientAddress CLIENT_PUBLIC_IPV6 "Public client IPv6" "" ipv6 public
	fi

	if ! validateClientAddressMode \
		"${CLIENT_ADDRESS_MODE}" \
		"${CLIENT_PRIVATE_IPV4}" \
		"${CLIENT_PUBLIC_IPV4}" \
		"${CLIENT_PRIVATE_IPV6}" \
		"${CLIENT_PUBLIC_IPV6}"; then
		echo ""
		echo -e "${RED}The selected client address mode (${CLIENT_ADDRESS_MODE}) does not match the provided addresses.${NC}"
		exit 1
	fi

	# Generate key pair for the client
	CLIENT_PRIV_KEY=$(wg genkey)
	CLIENT_PUB_KEY=$(echo "${CLIENT_PRIV_KEY}" | wg pubkey)
	CLIENT_PRE_SHARED_KEY=$(wg genpsk)

	HOME_DIR=$(getHomeDirForClient "${CLIENT_NAME}")
	CLIENT_FILE="${HOME_DIR}/${SERVER_WG_NIC}-client-${CLIENT_NAME}.conf"

	# Create client file and add the server as a peer
	printf '%s\n' "$(buildClientConfig \
		"${SERVER_WG_MTU}" \
		"${CLIENT_PRIV_KEY}" \
		"${SERVER_PUB_KEY}" \
		"${CLIENT_PRE_SHARED_KEY}" \
		"${ENDPOINT}" \
		"${ALLOWED_IPS}" \
		"${CLIENT_DNS_1}" \
		"${CLIENT_DNS_2}" \
		"${CLIENT_PRIVATE_IPV4}" \
		"${CLIENT_PUBLIC_IPV4}" \
		"${CLIENT_PRIVATE_IPV6}" \
		"${CLIENT_PUBLIC_IPV6}")" >"${CLIENT_FILE}"
	chmod 600 "${CLIENT_FILE}"
	chown --reference="${HOME_DIR}" "${CLIENT_FILE}"

	# Add the client as a peer to the server
	NEW_PEER_BLOCK=$(buildServerPeerBlock \
		"${CLIENT_NAME}" \
		"${CLIENT_ADDRESS_MODE}" \
		"${CLIENT_PUB_KEY}" \
		"${CLIENT_PRE_SHARED_KEY}" \
		"${CLIENT_PRIVATE_IPV4}" \
		"${CLIENT_PUBLIC_IPV4}" \
		"${CLIENT_PRIVATE_IPV6}" \
		"${CLIENT_PUBLIC_IPV6}")
	EXISTING_PEER_BLOCKS=$(getPeerBlocksFromConfig "${WG_CONF_FILE}")

	if [[ -n ${EXISTING_PEER_BLOCKS} ]]; then
		PEER_BLOCKS="${EXISTING_PEER_BLOCKS}

${NEW_PEER_BLOCK}"
	else
		PEER_BLOCKS="${NEW_PEER_BLOCK}"
	fi

	applyServerConfig "${PEER_BLOCKS}"

	# Generate QR code if qrencode is installed
	if command -v qrencode &>/dev/null; then
		echo -e "${GREEN}\nHere is your client config file as a QR Code:\n${NC}"
		qrencode -t ansiutf8 -l L <"${CLIENT_FILE}"
		echo ""
	fi

	echo -e "${GREEN}Your client config file is in ${CLIENT_FILE}${NC}"
}

function listClients() {
	NUMBER_OF_CLIENTS=$(grep -c -E "^### Client" "/etc/wireguard/${SERVER_WG_NIC}.conf")
	if [[ ${NUMBER_OF_CLIENTS} -eq 0 ]]; then
		echo ""
		echo "You have no existing clients!"
		exit 1
	fi

	grep -E "^### Client" "/etc/wireguard/${SERVER_WG_NIC}.conf" | cut -d ' ' -f 3 | nl -s ') '
}

function revokeClient() {
	local WG_CONF_FILE="/etc/wireguard/${SERVER_WG_NIC}.conf"

	NUMBER_OF_CLIENTS=$(grep -c -E "^### Client" "${WG_CONF_FILE}")
	if [[ ${NUMBER_OF_CLIENTS} == '0' ]]; then
		echo ""
		echo "You have no existing clients!"
		exit 1
	fi

	echo ""
	echo "Select the existing client you want to revoke"
	grep -E "^### Client" "${WG_CONF_FILE}" | cut -d ' ' -f 3 | nl -s ') '
	until [[ ${CLIENT_NUMBER} -ge 1 && ${CLIENT_NUMBER} -le ${NUMBER_OF_CLIENTS} ]]; do
		if [[ ${CLIENT_NUMBER} == '1' ]]; then
			read -rp "Select one client [1]: " CLIENT_NUMBER
		else
			read -rp "Select one client [1-${NUMBER_OF_CLIENTS}]: " CLIENT_NUMBER
		fi
	done

	# match the selected number to a client name
	CLIENT_NAME=$(grep -E "^### Client" "${WG_CONF_FILE}" | cut -d ' ' -f 3 | sed -n "${CLIENT_NUMBER}"p)

	# remove generated client file
	HOME_DIR=$(getHomeDirForClient "${CLIENT_NAME}")
	rm -f "${HOME_DIR}/${SERVER_WG_NIC}-client-${CLIENT_NAME}.conf"

	# regenerate the server configuration without the [Peer] block of this client
	PEER_BLOCKS=$(getPeerBlocksFromConfig "${WG_CONF_FILE}" | sed "/^### Client ${CLIENT_NAME}\$/,/^$/d")
	applyServerConfig "${PEER_BLOCKS}"
}

function uninstallWg() {
	echo ""
	echo -e "\n${RED}WARNING: This will uninstall WireGuard and remove all the configuration files!${NC}"
	echo -e "${ORANGE}Please backup the /etc/wireguard directory if you want to keep your configuration files.\n${NC}"
	read -rp "Do you really want to remove WireGuard? [y/n]: " -e REMOVE
	REMOVE=${REMOVE:-n}
	if [[ $REMOVE == 'y' ]]; then
		removePublicIpv4AnnouncementService

		systemctl disable --now "wg-quick@${SERVER_WG_NIC}"
		nft delete table inet wireguard 2>/dev/null

		case "${OS_FAMILY}" in
		debian)
			apt-get -o DPkg::Lock::Timeout=300 remove -y wireguard wireguard-tools qrencode
			;;
		rhel)
			dnf remove -y --noautoremove wireguard-tools qrencode
			if [[ ${OS} != 'fedora' && ${VERSION_ID%%.*} == 8 ]]; then
				dnf remove -y --noautoremove kmod-wireguard
			fi
			;;
		arch)
			local PACKAGE
			for PACKAGE in wireguard-tools qrencode; do
				if pacman -Qi "${PACKAGE}" &>/dev/null; then
					pacman -Rs --noconfirm "${PACKAGE}"
				fi
			done
			;;
		suse)
			zypper --non-interactive remove wireguard-tools qrencode
			;;
		flatcar)
			# Flatcar ships WireGuard in its read-only /usr, nothing to remove
			;;
		esac

		rm -rf /etc/wireguard
		rm -f /etc/sysctl.d/wg.conf

		# Removing the file does not unset anything, so the routing-only value is reset by hand
		if [[ ${PUBLIC_ROUTING_MODE} == 'yes' ]]; then
			sysctl -q -w net.ipv6.conf.all.proxy_ndp=0
		fi

		# Check if WireGuard is running
		systemctl is-active --quiet "wg-quick@${SERVER_WG_NIC}"
		WG_RUNNING=$?

		if [[ ${WG_RUNNING} -eq 0 ]]; then
			echo "WireGuard failed to uninstall properly."
			exit 1
		else
			echo "WireGuard uninstalled successfully."
			exit 0
		fi
	else
		echo ""
		echo "Removal aborted!"
	fi
}

function loadParams() {
	source /etc/wireguard/params

	# Installations made by earlier versions lack these keys
	SERVER_WG_MTU=${SERVER_WG_MTU:-1420}
}

function manageMenu() {
	echo "Welcome to WireGuard-install!"
	echo "The git repository is available at: https://github.com/tbringuier/wireguard-install"
	echo ""
	echo "It looks like WireGuard is already installed."
	echo ""
	echo "What do you want to do?"
	echo "   1) Add a new user"
	echo "   2) List all users"
	echo "   3) Revoke existing user"
	echo "   4) Uninstall WireGuard"
	echo "   5) Exit"
	until [[ ${MENU_OPTION} =~ ^[1-5]$ ]]; do
		read -rp "Select an option [1-5]: " MENU_OPTION
	done
	case "${MENU_OPTION}" in
	1)
		newClient
		;;
	2)
		listClients
		;;
	3)
		revokeClient
		;;
	4)
		uninstallWg
		;;
	5)
		exit 0
		;;
	esac
}

if [[ "${WG_INSTALL_TESTING:-0}" != 1 ]]; then
	# Check for root, virt, OS...
	initialCheck

	# Check if WireGuard is already installed and load params
	if [[ -e /etc/wireguard/params ]]; then
		loadParams
		manageMenu
	else
		installWireGuard
	fi
fi
